def areanvolume_of_cube(side):
    areaooneside=side*side;
    surfaceareaofallsides=areaooneside*6
    volume_of_cube=side**3
    return surfaceareaofallsides,volume_of_cube


def areanvolume_of_spear(radius):
    area_of_spear=3.14*4*radius*radius
    volume_of_spear=(4/3)*3.14*(radius**3)
    return area_of_spear,volume_of_spear


